#!/usr/bin/env node
// Generates src/types/database.ts from the isolated local Supabase stack (synthetic data only).
//
//   node scripts/generate-database-types.mjs            write src/types/database.ts from this checkout's stack
//   node scripts/generate-database-types.mjs --check    graph check: pass when the committed header matches the
//                                                       current migrations hash; otherwise regenerate into a temp
//                                                       file (needs this checkout's stack) and fail as stale
//   ... --check --regenerate --out <file>               always regenerate (local:verify/CI) and compare bytes
//
// Only the guarded local wrappers are used: no linked project, remote database URL or credential is accepted.
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { assertLocalConfig, assertLocalContainer, assertLocalDocker, supabaseCommand } from './_lib/local-environment.mjs'

export const TYPES_PATH = 'src/types/database.ts'
const MIGRATIONS = 'supabase/migrations'

export function migrationsHash(root = process.cwd()) {
  const cli = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).devDependencies.supabase
  const hash = createHash('sha256').update(`supabase-cli@${cli}\0`)
  for (const name of readdirSync(join(root, MIGRATIONS)).filter(name => name.endsWith('.sql')).sort()) {
    hash.update(`${name}\0`).update(readFileSync(join(root, MIGRATIONS, name))).update('\0')
  }
  return hash.digest('hex')
}

export function header(hash) {
  return [
    '// Generated by scripts/generate-database-types.mjs from the isolated local Supabase stack. Do not edit.',
    '// Regenerate after any migration change: npm run db:types (requires this checkout\'s local stack).',
    `// migrations-sha256: ${hash}`,
    '',
  ].join('\n')
}

export function committedHash(text) {
  return /^\/\/ migrations-sha256: ([0-9a-f]{64})$/m.exec(text)?.[1] ?? null
}

function generate() {
  assertLocalConfig(); assertLocalDocker(); assertLocalContainer()
  const body = supabaseCommand(['gen', 'types', 'typescript', '--local', '--schema', 'public'])
  if (!/export type Database = /.test(body)) throw new Error('Supabase CLI did not return a Database type')
  return header(migrationsHash()) + body.replace(/\s*$/, '\n')
}

function readCommitted() {
  try { return readFileSync(TYPES_PATH, 'utf8') } catch { return null }
}

function writeOut(path, text) {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
}

function firstDifference(a, b) {
  const left = a.split('\n'), right = b.split('\n')
  for (let i = 0; i < Math.max(left.length, right.length); i++) {
    if (left[i] !== right[i]) return `line ${i + 1}: committed ${JSON.stringify(left[i] ?? '<eof>')} vs generated ${JSON.stringify(right[i] ?? '<eof>')}`
  }
  return 'no textual difference'
}

async function main() {
  const args = process.argv.slice(2)
  const check = args.includes('--check')
  const regenerate = args.includes('--regenerate')
  const outIndex = args.indexOf('--out')
  const out = outIndex >= 0 ? args[outIndex + 1] : null
  const known = new Set(['--check', '--regenerate', '--out', out])
  const unknown = args.filter(arg => !known.has(arg))
  if (unknown.length || (outIndex >= 0 && !out)) throw new Error(`Unsupported option: ${unknown.join(' ') || '--out needs a path'}`)

  if (!check) {
    const text = generate()
    writeOut(TYPES_PATH, text)
    console.log(`Wrote ${TYPES_PATH} (migrations-sha256 ${migrationsHash().slice(0, 12)}).`)
    return
  }

  const committed = readCommitted()
  const current = migrationsHash()
  if (!regenerate && committed && committedHash(committed) === current) {
    console.log(`${TYPES_PATH} matches migrations-sha256 ${current.slice(0, 12)}; regeneration skipped (migrations unchanged).`)
    return
  }

  let generated
  try {
    generated = generate()
  } catch (error) {
    const state = regenerate ? 'could not be regenerated' : committed ? 'is stale (its migrations-sha256 header differs)' : 'is missing'
    throw new Error(`${TYPES_PATH} ${state} for migrations-sha256 ${current.slice(0, 12)}; this checkout's isolated stack is unavailable (${String(error.message).split('\n')[0]}). Run npm run local:start then npm run db:types, and commit the result.`)
  }
  const target = out || join('.tmp', 'database-types', `database-${Date.now()}.ts`)
  writeOut(target, generated)
  if (committed !== generated) {
    throw new Error(`${TYPES_PATH} differs from the types generated from migrations (${committed ? firstDifference(committed, generated) : 'file missing'}). Generated copy: ${target}. Run npm run db:types and commit it.`)
  }
  console.log(`${TYPES_PATH} is byte-identical to types regenerated from the isolated stack (${target}).`)
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch(error => { console.error(error.message); process.exitCode = 1 })
}
